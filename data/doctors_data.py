# Кэш photo file_id по имени врача (заполняется из photo_ids.json и при первой отправке)
PHOTO_IDS: dict[str, str] = {}


def _load_photo_ids() -> None:
    """Загружает сохранённые photo file_id из JSON."""
    global PHOTO_IDS
    if PHOTO_IDS_FILE.exists():
        try:
            PHOTO_IDS = json.loads(PHOTO_IDS_FILE.read_text(encoding='utf-8'))
        except Exception:
            PHOTO_IDS = {}


def get_photo_id(doctor_name: str) -> Optional[str]:
    """Возвращает сохранённый file_id фото врача или None."""
    return PHOTO_IDS.get(doctor_name)


def save_photo_id(doctor_name: str, file_id: str) -> None:
    """Сохраняет file_id фото врача в JSON и в кэш."""
    PHOTO_IDS[doctor_name] = file_id
    try:
        PHOTO_IDS_FILE.parent.mkdir(parents=True, exist_ok=True)
        PHOTO_IDS_FILE.write_text(json.dumps(PHOTO_IDS, ensure_ascii=False, indent=2), encoding='utf-8')
    except Exception:
        pass


